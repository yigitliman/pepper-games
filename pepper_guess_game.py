def main():
    parser = argparse.ArgumentParser(description='Pepper guessing (riddle) game.')
    parser.add_argument('-ip', '--ip', type=str, default='192.168.137.214')
    parser.add_argument('-port', '--port', type=int, default=NAOQI_PORT)
    parser.add_argument('-ssh_port', '--ssh_port', type=int, default=22)
    parser.add_argument('-u', '--username', type=str, default='nao')
    parser.add_argument('-p', '--password', type=str,
                        default=os.environ.get(PEPPER_PW_ENV_VAR),
                        help='Pepper ssh password (or set %s)' % PEPPER_PW_ENV_VAR)
    parser.add_argument('-d', '--duration', type=int, default=5,
                        help='seconds to record each guess')
    parser.add_argument('-l', '--lang', type=str, default='en', choices=['en', 'de'])
    parser.add_argument('-c', '--category', type=str, default='mixed',
                        choices=['animals', 'countries', 'cities', 'mixed'])
    parser.add_argument('-a', '--attempts', type=int, default=5,
                        help='wrong guesses allowed before the answer is revealed')
    parser.add_argument('-r', '--rounds', type=int, default=0,
                        help='number of items (0 = endless until Ctrl+C)')
    parser.add_argument('-ra', '--remote_audio_path', type=str,
                        default='/home/nao/recording.wav')
    parser.add_argument('-la', '--local_audio_path', type=str,
                        default='./recording.wav')
    parser.add_argument('--kiosk', action='store_true',
                        help='internal: set when launched by the tablet kiosk menu '
                             '(so EXIT does not spawn a second kiosk process)')
    args = parser.parse_args()

    if not STT_BASE_URL:
        print('ERROR: set the %s environment variable first.' % BASE_URL_ENV_VAR)
        print('  Windows:  set %s=https://your-open-webui-server'
              % BASE_URL_ENV_VAR)
        sys.exit(1)
    token = os.environ.get(TOKEN_ENV_VAR)
    if not token:
        print('ERROR: set the %s environment variable first.' % TOKEN_ENV_VAR)
        sys.exit(1)
    if not args.password:
        print('ERROR: set the %s environment variable, or pass -p <password>.'
              % PEPPER_PW_ENV_VAR)
        sys.exit(1)

    ph = PHRASES[args.lang]

    ip = find_pepper(args.ip)
    if not ip:
        print('could not find Pepper on the %s.x network.' % HOTSPOT_SUBNET)
        sys.exit(1)

    session = qi.Session()
    try:
        session.connect('tcp://%s:%d' % (ip, args.port))
    except RuntimeError:
        print('cannot connect to Pepper at %s:%d' % (ip, args.port))
        sys.exit(1)
    print('connected to Pepper at %s:%d' % (ip, args.port))

    tts = session.service('ALTextToSpeech')
    tts.setLanguage(ph['tts'])
    try:
        memory = session.service('ALMemory')
        memory.insertData(HINT_KEY, 0)
        memory.insertData(SKIP_KEY, 0)
        memory.insertData(STOP_KEY, 0)
        memory.insertData(EXIT_KEY, 0)
    except Exception:
        memory = None

    sftp_info = None
    try:
        import paramiko
        ssh = paramiko.SSHClient()
        ssh.set_missing_host_key_policy(paramiko.AutoAddPolicy())
        ssh.connect(ip, args.ssh_port, args.username, args.password, timeout=10)
        sftp_info = (ssh, ssh.open_sftp())
    except Exception as err:
        print('note: tablet uploads disabled (%s)' % err)

    def read_int(key):
        if not memory:
            return 0
        try:
            return int(memory.getData(key))
        except Exception:
            return 0

    categories = ['animals', 'countries', 'cities'] if args.category == 'mixed' \
        else [args.category]
    recent = []
    base_stop = read_int(STOP_KEY)
    base_exit = read_int(EXIT_KEY)

    def quit_requested():
        return read_int(STOP_KEY) > base_stop or read_int(EXIT_KEY) > base_exit

    tts.say(ph['welcome'])

    rounds = 0
    quit_game = False
    try:
        while not quit_game and (args.rounds == 0 or rounds < args.rounds):
            rounds += 1
            category = random.choice(categories)
            pool = [w for w in WORDS[category] if w not in recent] or WORDS[category]
            secret = random.choice(pool)
            recent = (recent + [secret])[-8:]
            print('\n=== round %d: %s = %s ===' % (rounds, category, secret))

            set_eyes(session, 0x00A000)
            tts.say(ph['think'])
            try:
                clue, hints, answer_label = gen_riddle(secret, CAT_NOUN[category],
                                                       ph['tts'], token)
            except Exception as err:
                print('riddle generation failed: %s' % err)
                rounds -= 1
                continue
            set_eyes(session, None)
            print('clue: %s' % clue.encode('utf-8'))

            cat_label = ph['cattab'][category]
            if sftp_info:
                show_riddle_tablet(session, sftp_info, cat_label, ph['tab_main'],
                                   ph['hint_btn'], ph['skip_btn'],
                                   ph['stop_btn'], ph['exit_btn'])
            last_hintreq = read_int(HINT_KEY)
            last_skipreq = read_int(SKIP_KEY)
            hint_idx = [0]

            def give_hint():
                if hint_idx[0] < len(hints):
                    tts.say(ph['hint_intro'])
                    tts.say(hints[hint_idx[0]].encode('utf-8'))
                    if sftp_info:
                        show_riddle_tablet(session, sftp_info, cat_label,
                                           hints[hint_idx[0]], ph['hint_btn'],
                                           ph['skip_btn'], ph['stop_btn'], ph['exit_btn'])
                    hint_idx[0] += 1
                else:
                    tts.say(ph['no_more_hints'])

            tts.say(clue.encode('utf-8'))

            solved = False
            skipped = False
            attempts_left = args.attempts
            while attempts_left > 0:
                # STOP/EXIT button -> quit the game (back to the menu if kiosked)
                if quit_requested():
                    quit_game = True
                    break
                # tablet buttons pressed since last check?
                if read_int(SKIP_KEY) > last_skipreq:
                    skipped = True
                    break
                cur = read_int(HINT_KEY)
                if cur > last_hintreq:
                    last_hintreq = cur
                    give_hint()
                    continue

                set_eyes(session, 0x0000FF)
                # poll_fn lets tablet buttons interrupt the recording immediately
                aborted = record_audio(session, args.remote_audio_path, args.duration,
                                       cue=ph['guess_now'], poll_fn=quit_requested)
                set_eyes(session, None)
                if aborted or quit_requested():
                    quit_game = True
                    break
                download_audio(ip, args.ssh_port, args.username, args.password,
                               args.remote_audio_path, args.local_audio_path)
                guess = transcribe(args.local_audio_path, token, args.lang)

                # a tablet tap may have arrived during recording
                if quit_requested():
                    quit_game = True
                    break
                if read_int(SKIP_KEY) > last_skipreq:
                    skipped = True
                    break
                cur = read_int(HINT_KEY)
                if cur > last_hintreq:
                    last_hintreq = cur
                    give_hint()
                    continue

                alnum = [c for c in guess if c.isalnum()] if guess else []
                if len(alnum) < 2:
                    tts.say(ph['nothing'])
                    continue

                low = guess.lower()
                if any(w in low for w in ph['skipwords']):
                    skipped = True
                    break
                if any(w in low for w in ph['hintwords']):
                    give_hint()
                    continue

                if is_correct(secret, guess, ph['tts'], token):
                    solved = True
                    break
                attempts_left -= 1
                tts.say(ph['wrong'])

            if quit_game:
                break
            if solved:
                set_eyes(session, 0x00A000)
                tts.say(ph['correct'])
                tts.say((ph['reveal'] % answer_label).encode('utf-8'))
                if sftp_info:
                    show_on_tablet(session, sftp_info, ph['correct'], answer_label,
                                   bg='#1b7f4b', stop_label=ph['stop_btn'],
                                   exit_label=ph['exit_btn'])
            else:
                if skipped:
                    tts.say(ph['skip_intro'])
                tts.say((ph['reveal'] % answer_label).encode('utf-8'))
                if sftp_info:
                    show_on_tablet(session, sftp_info, u'', answer_label,
                                   bg='#b8860b', stop_label=ph['stop_btn'],
                                   exit_label=ph['exit_btn'])
            set_eyes(session, None)
            time.sleep(2)
        exited_via_menu = quit_game and read_int(EXIT_KEY) > base_exit
        if quit_game and sftp_info and not exited_via_menu:
            # STOP was tapped (not EXIT): leave the tablet on a neutral,
            # button-free screen instead of a frozen page with dead buttons
            show_on_tablet(session, sftp_info, u'', ph['goodbye'],
                           bg='#12203a', show_controls=False)
        tts.say(ph['goodbye'])
        if exited_via_menu and not args.kiosk:
            # EXIT was tapped and nothing else is going to bring the game
            # menu back (we were not launched by the kiosk) -- do it ourselves
            relaunch_kiosk_menu(ip)
    except KeyboardInterrupt:
        print('\nstopping game ...')
        try:
            tts.say(ph['goodbye'])
        except Exception:
            pass
    finally:
        set_eyes(session, None)
        if sftp_info:
            try:
                sftp_info[1].close(); sftp_info[0].close()
            except Exception:
                pass
    print('total items played: %d' % rounds)


if __name__ == '__main__':
    main()
