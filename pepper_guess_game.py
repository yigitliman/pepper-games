        u'.cat{font-size:5vw;letter-spacing:.3vw;opacity:.8;margin-bottom:3vh}'
        u'.main{font-size:6.5vw;font-weight:bold;line-height:1.25;margin-bottom:6vh}'
        u'.btns{display:flex;flex-wrap:wrap;justify-content:center;gap:3vw}'
        u'button{font-size:4.6vw;font-weight:bold;border:none;border-radius:4vw;'
        u'padding:2.6vh 5vw}button:active{transform:translateY(1vh);box-shadow:none!important}'
        u'#hb{color:#3d2b7a;background:#ffd23f;box-shadow:0 1vh 0 #c99a00}'
        u'#sb{color:#fff;background:#6b5aa8;box-shadow:0 1vh 0 #473b73}'
        u'#tb{color:#fff;background:#c0392b;box-shadow:0 1vh 0 #7d2016}'
        u'#eb{color:#fff;background:#555b6e;box-shadow:0 1vh 0 #33373f}'
        u'</style><script src="qimessaging.js"></script></head><body>'
        u'<div class="cat">%s</div><div class="main">%s</div>'
        u'<div class="btns"><button id="hb" onclick="tap(\'hb\',\'%s\')">%s</button>'
        u'<button id="sb" onclick="tap(\'sb\',\'%s\')">%s</button>'
        u'<button id="tb" onclick="tap(\'tb\',\'%s\')">%s</button>'
        u'<button id="eb" onclick="tap(\'eb\',\'%s\')">%s</button></div>'
        u'<script>var M=null;'
        u'function conn(){try{QiSession(function(s){var p=s.service("ALMemory");'
        u'var set=function(m){M=m;};if(p.then)p.then(set);else if(p.done)p.done(set);},'
